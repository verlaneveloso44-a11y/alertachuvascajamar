         -23.3560::DOUBLE PRECISION, -46.8760::DOUBLE PRECISION),
        ('Estacao Jordanesia 01', 'EJ01', 'Jordanesia',
         -23.3550::DOUBLE PRECISION, -46.8780::DOUBLE PRECISION),
        ('Estacao Polvilho 01', 'EP01', 'Polvilho',
         -23.3930::DOUBLE PRECISION, -46.8370::DOUBLE PRECISION)
) AS dados(nome_estacao, codigo_estacao, nome_bairro, latitude, longitude)
INNER JOIN public.bairros AS b
    ON LOWER(BTRIM(b.nome_bairro)) = LOWER(BTRIM(dados.nome_bairro))
   AND LOWER(BTRIM(b.municipio)) = 'cajamar'
WHERE NOT EXISTS (
    SELECT 1
    FROM public.estacoes AS e
    WHERE e.codigo_estacao = dados.codigo_estacao
);

-- Preenche localizacao de estacoes antigas que tenham coordenadas.
UPDATE public.estacoes
SET localizacao = ST_SetSRID(
    ST_MakePoint(longitude, latitude),
    4326
)
WHERE localizacao IS NULL
  AND latitude IS NOT NULL
  AND longitude IS NOT NULL;

