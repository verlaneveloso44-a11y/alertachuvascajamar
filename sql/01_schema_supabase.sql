-- Cria as restricoes de chave estrangeira somente se ainda nao existirem.
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'fk_estacoes_bairros'
          AND conrelid = 'public.estacoes'::regclass
    ) THEN
        ALTER TABLE public.estacoes
            ADD CONSTRAINT fk_estacoes_bairros
            FOREIGN KEY (id_bairro)
            REFERENCES public.bairros(id_bairro);
    END IF;
END $$;

